import os
import pandas as pd
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils.dataframe import dataframe_to_rows

def generate_excel_mis_report(
    df: pd.DataFrame,
    output_path: str,
    report_title: str = "Executive MIS Performance Report",
    dataset_name: str = None,
    imputation_details: list = None
):
    wb = Workbook()

    # Sheet 1: Executive KPI Overview
    ws_kpi = wb.active
    ws_kpi.title = "Executive Summary"
    ws_kpi.views.sheetView[0].showGridLines = True

    # Styling definitions
    title_font = Font(name="Calibri", size=16, bold=True, color="1E3A8A")
    section_font = Font(name="Calibri", size=12, bold=True, color="1E293B")
    header_font = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
    header_fill = PatternFill(start_color="2563EB", end_color="2563EB", fill_type="solid")
    kpi_fill = PatternFill(start_color="EFF6FF", end_color="EFF6FF", fill_type="solid")
    border_thin = Border(
        left=Side(style='thin', color='E2E8F0'),
        right=Side(style='thin', color='E2E8F0'),
        top=Side(style='thin', color='E2E8F0'),
        bottom=Side(style='thin', color='E2E8F0')
    )

    # Title block
    ws_kpi["B2"] = report_title
    ws_kpi["B2"].font = title_font
    ws_kpi["B3"] = (
        f"Source Dataset: {dataset_name} • Generated by ExecuMate AI"
        if dataset_name
        else "Generated by ExecuMate AI Platform • Executive Briefing"
    )
    ws_kpi["B3"].font = Font(name="Calibri", size=10, italic=True, color="64748B")

    # Metrics Summary Box
    ws_kpi["B5"] = "Key Performance Indicator"
    ws_kpi["C5"] = "Metric Value"
    ws_kpi["B5"].font = header_font
    ws_kpi["B5"].fill = header_fill
    ws_kpi["C5"].font = header_font
    ws_kpi["C5"].fill = header_fill

    row_count = len(df)
    col_count = len(df.columns)
    remaining_nulls = int(df.isnull().sum().sum()) if row_count > 0 else 0

    kpis = [
        ("Source Dataset", dataset_name or "Uploaded Dataset"),
        ("Total Records", f"{row_count:,}"),
        ("Total Columns", f"{col_count:,}"),
        ("Remaining Null Cells", f"{remaining_nulls:,}"),
        ("Reporting Status", "Audited & Cleaned" if remaining_nulls == 0 else "Raw Snapshot"),
    ]

    numeric_cols = [c for c in df.columns if pd.api.types.is_numeric_dtype(df[c])]
    non_id_numeric = [c for c in numeric_cols if str(c).lower() not in {"id", "sr_no", "index"}]
    for col in (non_id_numeric or numeric_cols)[:5]:
        valid = df[col].dropna()
        if not valid.empty:
            kpis.append((f"{col} — Total", f"{float(valid.sum()):,.2f}"))
            kpis.append((f"{col} — Mean (Avg)", f"{float(valid.mean()):,.2f}"))
            kpis.append((f"{col} — Median", f"{float(valid.median()):,.2f}"))
            kpis.append((f"{col} — Max", f"{float(valid.max()):,.2f}"))

    current_row = 6
    for k, v in kpis:
        ws_kpi[f"B{current_row}"] = k
        ws_kpi[f"C{current_row}"] = v
        ws_kpi[f"B{current_row}"].border = border_thin
        ws_kpi[f"C{current_row}"].border = border_thin
        ws_kpi[f"B{current_row}"].fill = kpi_fill
        ws_kpi[f"C{current_row}"].font = Font(bold=True)
        current_row += 1

    if imputation_details:
        current_row += 1
        ws_kpi[f"B{current_row}"] = "Null Imputation Audit"
        ws_kpi[f"B{current_row}"].font = section_font
        current_row += 1
        for col_idx, heading in enumerate(["Column", "Method Used", "Replacement Value", "Nulls Replaced"], start=2):
            cell = ws_kpi.cell(row=current_row, column=col_idx, value=heading)
            cell.font = header_font
            cell.fill = header_fill
        current_row += 1
        for item in imputation_details:
            ws_kpi.cell(row=current_row, column=2, value=str(item.get("column", ""))).border = border_thin
            ws_kpi.cell(row=current_row, column=3, value=str(item.get("method", ""))).border = border_thin
            ws_kpi.cell(row=current_row, column=4, value=item.get("value", "")).border = border_thin
            ws_kpi.cell(row=current_row, column=5, value=item.get("count", item.get("nulls_replaced", 0))).border = border_thin
            current_row += 1

    # Segment Breakdown Table (First categorical column vs primary numeric column)
    text_cols = [c for c in df.columns if c not in numeric_cols and not any(tok in str(c).lower() for tok in ("date", "time", "id"))]
    primary_metric = (non_id_numeric or numeric_cols)[0] if (non_id_numeric or numeric_cols) else None
    if text_cols and primary_metric:
        group_col = text_cols[0]
        grouped = (
            df.groupby(group_col, dropna=False)[primary_metric]
            .agg(["count", "sum", "mean"])
            .sort_values(by="sum", ascending=False)
            .head(10)
        )
        if not grouped.empty:
            current_row += 1
            ws_kpi[f"B{current_row}"] = f"Top Breakdown: {primary_metric} by {group_col}"
            ws_kpi[f"B{current_row}"].font = section_font
            current_row += 1
            for col_idx, heading in enumerate([str(group_col), "Records", f"Total {primary_metric}", f"Avg {primary_metric}"], start=2):
                cell = ws_kpi.cell(row=current_row, column=col_idx, value=heading)
                cell.font = header_font
                cell.fill = header_fill
            current_row += 1
            for seg_name, row_stats in grouped.iterrows():
                ws_kpi.cell(row=current_row, column=2, value=str(seg_name)).border = border_thin
                ws_kpi.cell(row=current_row, column=3, value=int(row_stats["count"])).border = border_thin
                ws_kpi.cell(row=current_row, column=4, value=round(float(row_stats["sum"]), 2)).border = border_thin
                ws_kpi.cell(row=current_row, column=5, value=round(float(row_stats["mean"]), 2)).border = border_thin
                current_row += 1

    ws_kpi.column_dimensions["B"].width = 34
    ws_kpi.column_dimensions["C"].width = 26
    ws_kpi.column_dimensions["D"].width = 24
    ws_kpi.column_dimensions["E"].width = 22

    # Sheet 2: Cleaned Data
    ws_data = wb.create_sheet(title="Detailed Cleaned Data")
    ws_data.views.sheetView[0].showGridLines = True

    for r_idx, row in enumerate(dataframe_to_rows(df, index=False, header=True), start=1):
        ws_data.append(row)
        if r_idx == 1:
            for cell in ws_data[1]:
                cell.font = header_font
                cell.fill = header_fill
                cell.alignment = Alignment(horizontal="center")
        else:
            for cell in ws_data[r_idx]:
                cell.border = border_thin

    for col in ws_data.columns:
        max_len = max(len(str(cell.value or '')) for cell in col)
        col_letter = col[0].column_letter
        ws_data.column_dimensions[col_letter].width = min(max(max_len + 4, 12), 45)

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    wb.save(output_path)
    return output_path

